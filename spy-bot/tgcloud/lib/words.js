/** Темы: { name, groups: [[похожие слова]], words: все слова темы }. */
export const CATEGORIES = Object.fromEntries(Object.entries(THEMES).map(([key, t]) => [key, { ...t, words: t.groups.flat() }]));

export const CATEGORY_KEYS = Object.keys(CATEGORIES);
export const ANY = 'any';

/** 'places' → 'места'; 'any' → 'любая'. */
export const categoryName = (key) => (key === ANY ? 'любая' : CATEGORIES[key]?.name ?? key);

/** Похожие на word слова (из его группы), без самого word. */
export function similarWords(category, word) {
  return (CATEGORIES[category]?.groups.find((g) => g.includes(word)) ?? []).filter((w) => w !== word);
}
